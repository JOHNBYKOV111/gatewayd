package usage

// EstimateTokens возвращает приблизительное количество токенов в тексте.
//
// Это НЕ точный подсчёт (для точного нужен токенизатор модели, например tiktoken
// для OpenAI или аналог для конкретной модели). Оценка нужна для стримов, где
// usage приходит только в финальном чанке, а стоимость хочется учитывать раньше.
//
// Эвристика:
//   - латиница: примерно 4 символа на токен (0.25 токена на символ);
//   - кириллица: примерно 2 символа на токен (0.5 токена на символ) —
//     русские тексты в токенизаторах «дороже» латиницы;
//   - пробелы и знаки препинания учитываются как часть текста (грубо).
//
// Погрешность оценки: ±30–50% в зависимости от языка и текста.
// В README это честно указано: «стоимость стрима приблизительна до финального чанка».
func EstimateTokens(text string) int {
	if len(text) == 0 {
		return 0
	}

	// Считаем латиницу и кириллицу отдельно, чтобы не занижать оценку
	// для русских текстов.
	var latin, cyrillic int
	for _, r := range text {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z':
			latin++
		case r >= 'А' && r <= 'я', r == 'Ё', r == 'ё':
			cyrillic++
		default:
			// пробелы, цифры, пунктуация — считаем как латиницу (1 символ ≈ 0.25 токена).
			latin++
		}
	}

	// 4 символа латиницы ≈ 1 токен, 2 символа кириллицы ≈ 1 токен.
	latinTokens := latin / 4
	cyrillicTokens := cyrillic / 2

	total := latinTokens + cyrillicTokens
	if total == 0 {
		// Очень короткий текст (например, "a" или "я") — хотя бы 1 токен.
		total = 1
	}
	return total
}

// EstimatePromptTokens оценивает токены промпта по списку сообщений.
// Каждое сообщение оценивается через EstimateTokens, плюс небольшая надбавка
// на служебные токены роли (system/user/assistant) — примерно 3 токена на сообщение.
func EstimatePromptTokens(messages []string) int {
	if len(messages) == 0 {
		return 0
	}
	total := 0
	for _, m := range messages {
		total += EstimateTokens(m) + 3 // +3 на роль и разделители
	}
	return total
}
